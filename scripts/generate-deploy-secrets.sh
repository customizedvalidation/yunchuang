#!/usr/bin/env bash
# ==============================================================================
# 生成 K8s 部署凭据（2026-11-09 第三轮）
#
# 为什么要脚本生成：02-secret.yaml 的注释让运维分别随机生成 database-url 里的
# 口令与 postgres-password，但 17-postgresql.yaml 用 postgres-password 作为
# POSTGRES_PASSWORD 初始化数据库，后端又用 database-url 里的口令去连 —— 两者
# 不一致时清单全部 apply 成功、后端却在鉴权阶段启动失败，且错误发生在部署之后，
# 很难归因。本脚本强制两者同源。
#
# 用法：
#   bash scripts/generate-deploy-secrets.sh --out .env.deploy.k8s
#   bash scripts/generate-deploy-secrets.sh --from-env .env.deploy.k8s --gh-commands
#   bash scripts/generate-deploy-secrets.sh --from-env .env.deploy --all-gh-commands
#   bash scripts/generate-deploy-secrets.sh --pg-host <host> --pg-db <db> --pg-user <user>
#
# --gh-commands 只输出 6 个 K8s secret；--all-gh-commands 输出「全量」注入命令
# （三环境 12 项 + KUBE_CONFIG + DEPLOY_DIR + 6 个 K8s secret + 可选 K8S_BASE_URL），
# 对应 check-deploy-prereqs.sh --list 的全部配置类变量。总闸开关刻意不由此生成。
#
# 输出文件可被 check-deploy-prereqs.sh --env-file 直接读取；
# 默认不打印任何凭据明文，文件权限 600，.env.* 已被 .gitignore 忽略。
# ==============================================================================
set -euo pipefail

OUT=""
FROM_ENV=""
PRINT_GH=0
PRINT_ALL_GH=0
PG_HOST="postgresql.metaclouds.svc.cluster.local"
PG_PORT="5432"
PG_DB="metaclouds"
PG_USER="metaclouds_user"
SSLMODE="require"

while [ $# -gt 0 ]; do
  case "$1" in
    --out)           OUT="${2:-}"; shift 2 ;;
    --out=*)         OUT="${1#*=}"; shift ;;
    --from-env)      FROM_ENV="${2:-}"; shift 2 ;;
    --from-env=*)    FROM_ENV="${1#*=}"; shift ;;
    --gh-commands)   PRINT_GH=1; shift ;;
    --all-gh-commands) PRINT_ALL_GH=1; shift ;;
    --pg-host)       PG_HOST="${2:-}"; shift 2 ;;
    --pg-port)       PG_PORT="${2:-}"; shift 2 ;;
    --pg-db)         PG_DB="${2:-}"; shift 2 ;;
    --pg-user)       PG_USER="${2:-}"; shift 2 ;;
    --sslmode)       SSLMODE="${2:-}"; shift 2 ;;
    -h|--help)       echo "Usage: $0 [--out <file>] [--from-env <file> --gh-commands|--all-gh-commands] [--pg-host/--pg-db/--pg-user ...]"; exit 0 ;;
    *) echo "::error::unknown argument: $1" >&2; exit 2 ;;
  esac
done

# 纯字母数字随机串：避免 / + = 等字符在 URL、YAML、shell 中需要转义
gen() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9'; }

# ---------------------------------------------------------------------------
# --all-gh-commands：全量注入命令生成（2026-11-11 第八轮）
#
# 背景：--gh-commands 只输出 6 个 K8s secret，而 check-deploy-prereqs.sh
# --strict 实测的 13 项 FAIL 全在它覆盖范围之外。运维若以为「注入同一套
# 凭据就配齐了」而直接打开 DEPLOY_ENABLED，preflight 会立刻 exit 1。
# 本模式从一份 .env.deploy 生成全量命令；缺失项显式 SKIP + 告警，绝不
# 用本脚本新生成的随机值偷偷补齐（那会与本地 env 文件不一致）。
#
# 刻意排除三个总闸（DEPLOY_ENABLED / DEPLOY_TARGETS / REQUIRE_PG_HA）：
# 开关必须在 strict + verify-gh 全绿后由人工单独设置，脚本绝不代开。
# ---------------------------------------------------------------------------
ALL_GH_VARIABLES=(
  DEV_BASE_URL STAGING_BASE_URL PROD_BASE_URL
  K8S_BASE_URL
)
ALL_GH_SECRETS=(
  DEV_SSH_KEY DEV_HOST DEV_USER
  STAGING_SSH_KEY STAGING_HOST STAGING_USER
  PROD_SSH_KEY PROD_HOST PROD_USER
  DEPLOY_DIR
  KUBE_CONFIG
  K8S_JWT_SECRET K8S_DATABASE_URL K8S_REDIS_PASSWORD
  K8S_DEFAULT_ADMIN_PASSWORD K8S_POSTGRES_PASSWORD
  K8S_PROTECTED_ENDPOINTS_TOKEN
)

emit_gh_set() {
  local kind="$1" name="$2" val="$3"
  if [[ "$val" == *$'\n'* ]]; then
    # 多行值（SSH 私钥 PEM）走 quoted heredoc + stdin，避免 --body 的引号/换行歧义
    printf "gh %s set %s <<'DEPLOY_VALUE_EOF'\n" "$kind" "$name"
    printf '%s\n' "$val"
    printf 'DEPLOY_VALUE_EOF\n'
  else
    # 单引号包裹并转义内部单引号：' -> '\''
    printf "gh %s set %s --body '%s'\n" "$kind" "$name" "${val//\'/\'\\\'\'}"
  fi
}

run_all_gh_commands() {
  if [ -z "$FROM_ENV" ] || [ ! -f "$FROM_ENV" ]; then
    echo "::error::--all-gh-commands requires --from-env <file>" >&2
    exit 2
  fi
  # 与 check-deploy-prereqs.sh --env-file 同口径：source 本地 env 文件。
  # 明文只出现在生成的命令里，绝不写进日志/汇总。
  set -a
  # shellcheck disable=SC1090
  . "$FROM_ENV"
  set +a

  # 同源校验：database-url 里的口令必须与 postgres-password 一致
  local url_pass="${K8S_DATABASE_URL:-}"
  url_pass="${url_pass#*://}"; url_pass="${url_pass#*:}"; url_pass="${url_pass%%@*}"
  if [ -n "${K8S_DATABASE_URL:-}" ] && [ -n "${K8S_POSTGRES_PASSWORD:-}" ] \
     && [ "$url_pass" != "$K8S_POSTGRES_PASSWORD" ]; then
    echo "::error::K8S_DATABASE_URL password does not match K8S_POSTGRES_PASSWORD" >&2
    exit 2
  fi

  printf '# generated by generate-deploy-secrets.sh --all-gh-commands\n'
  printf '# source: %s  (values inlined below - review before piping to bash)\n' "$FROM_ENV"
  printf '# switches DEPLOY_ENABLED / DEPLOY_TARGETS / REQUIRE_PG_HA are NOT set here\n\n'

  local emitted=0 skipped=0 name val optional
  for name in "${ALL_GH_VARIABLES[@]}"; do
    val="${!name:-}"
    if [ -z "$val" ]; then
      optional=""; case "$name" in K8S_BASE_URL) optional=" (optional)";; esac
      printf '# SKIP variable %s%s (not set in %s)\n' "$name" "$optional" "$FROM_ENV"
      skipped=$((skipped + 1)); continue
    fi
    emit_gh_set variable "$name" "$val"; emitted=$((emitted + 1))
  done
  for name in "${ALL_GH_SECRETS[@]}"; do
    val="${!name:-}"
    if [ -z "$val" ]; then
      optional=""; case "$name" in DEPLOY_DIR) optional=" (optional, default /opt/metaclouds)";; esac
      printf '# SKIP secret %s%s (not set in %s)\n' "$name" "$optional" "$FROM_ENV"
      skipped=$((skipped + 1)); continue
    fi
    emit_gh_set secret "$name" "$val"; emitted=$((emitted + 1))
  done

  printf '\n# switches are set manually, only after strict + --verify-gh both pass:\n'
  printf "# gh variable set DEPLOY_TARGETS --body 'development,staging,production,k8s'\n"
  printf '# gh variable set DEPLOY_ENABLED --body true\n'
  printf -- '--- generated %d set command(s), skipped %d empty/optional value(s) ---\n' "$emitted" "$skipped" >&2
  if [ "$skipped" -gt 0 ]; then
    printf '::warning::%d value(s) empty in %s - skipped, NOT filled with random values\n' "$skipped" "$FROM_ENV" >&2
  fi
  exit 0
}

if [ "$PRINT_ALL_GH" -eq 1 ]; then
  if [ "$PRINT_GH" -eq 1 ]; then
    echo "::error::--gh-commands and --all-gh-commands are mutually exclusive" >&2
    exit 2
  fi
  run_all_gh_commands
fi

PG_PASSWORD="$(gen)"
K8S_JWT_SECRET="$(gen)"
K8S_DATABASE_URL="postgresql://${PG_USER}:${PG_PASSWORD}@${PG_HOST}:${PG_PORT}/${PG_DB}?sslmode=${SSLMODE}"
K8S_REDIS_PASSWORD="$(gen)"
K8S_DEFAULT_ADMIN_PASSWORD="$(gen)"
K8S_POSTGRES_PASSWORD="$PG_PASSWORD"
K8S_PROTECTED_ENDPOINTS_TOKEN="$(gen)"

# --from-env：复用已生成的凭据，保证 --gh-commands 注入 GitHub 的值与本地
# --env-file 自检的值完全一致（否则两次运行会生成两套不同的口令）。
if [ -n "$FROM_ENV" ]; then
  if [ ! -f "$FROM_ENV" ]; then
    echo "::error::--from-env file not found: $FROM_ENV" >&2
    exit 2
  fi
  set -a
  # shellcheck disable=SC1090
  . "$FROM_ENV"
  set +a
  for name in K8S_JWT_SECRET K8S_DATABASE_URL K8S_REDIS_PASSWORD \
              K8S_DEFAULT_ADMIN_PASSWORD K8S_POSTGRES_PASSWORD \
              K8S_PROTECTED_ENDPOINTS_TOKEN; do
    if [ -z "${!name:-}" ]; then
      echo "::error::$FROM_ENV is missing $name" >&2
      exit 2
    fi
  done
  # 一致性自检：database-url 里的口令必须与 postgres-password 相同
  URL_PASS="${K8S_DATABASE_URL#*://}"
  URL_PASS="${URL_PASS#*:}"
  URL_PASS="${URL_PASS%%@*}"
  if [ "$URL_PASS" != "$K8S_POSTGRES_PASSWORD" ]; then
    echo "::error::password inside K8S_DATABASE_URL does not match K8S_POSTGRES_PASSWORD" >&2
    exit 2
  fi
fi

if [ "$PRINT_GH" -eq 1 ]; then
  # 明文只在这里出现，且由调用方自行决定是否执行/转发
  printf "gh secret set K8S_JWT_SECRET --body '%s'\n" "$K8S_JWT_SECRET"
  printf "gh secret set K8S_DATABASE_URL --body '%s'\n" "$K8S_DATABASE_URL"
  printf "gh secret set K8S_REDIS_PASSWORD --body '%s'\n" "$K8S_REDIS_PASSWORD"
  printf "gh secret set K8S_DEFAULT_ADMIN_PASSWORD --body '%s'\n" "$K8S_DEFAULT_ADMIN_PASSWORD"
  printf "gh secret set K8S_POSTGRES_PASSWORD --body '%s'\n" "$K8S_POSTGRES_PASSWORD"
  printf "gh secret set K8S_PROTECTED_ENDPOINTS_TOKEN --body '%s'\n" "$K8S_PROTECTED_ENDPOINTS_TOKEN"
  printf '\n# 注意：K8S_POSTGRES_PASSWORD 与 K8S_DATABASE_URL 中的口令由本脚本保证同源。\n' >&2
  exit 0
fi

if [ -z "$OUT" ]; then
  echo "::error::specify --out <file> (or --gh-commands)" >&2
  exit 2
fi

TMP="$(mktemp "${OUT}.XXXXXX")"
chmod 600 "$TMP"
cat > "$TMP" <<EOF
# generated by scripts/generate-deploy-secrets.sh — DO NOT COMMIT
K8S_JWT_SECRET='${K8S_JWT_SECRET}'
K8S_DATABASE_URL='${K8S_DATABASE_URL}'
K8S_REDIS_PASSWORD='${K8S_REDIS_PASSWORD}'
K8S_DEFAULT_ADMIN_PASSWORD='${K8S_DEFAULT_ADMIN_PASSWORD}'
K8S_POSTGRES_PASSWORD='${K8S_POSTGRES_PASSWORD}'
K8S_PROTECTED_ENDPOINTS_TOKEN='${K8S_PROTECTED_ENDPOINTS_TOKEN}'
EOF
mv "$TMP" "$OUT"
chmod 600 "$OUT" 2>/dev/null || true

REPORTED_MODE="$(stat -c '%a' "$OUT" 2>/dev/null || echo unknown)"
echo "generated 6 K8s credentials into $OUT (values redacted, requested mode 600)"
if [ "$REPORTED_MODE" != "600" ]; then
  echo "  [WARN] filesystem reports mode $REPORTED_MODE — Windows/NTFS does not enforce POSIX chmod;"
  echo "         keep this file in a private directory and never commit it (.env.* is gitignored)"
fi
echo "  - K8S_POSTGRES_PASSWORD and the password inside K8S_DATABASE_URL are identical"
echo "  - verify with: bash scripts/check-deploy-prereqs.sh --env-file $OUT --target k8s --report"
echo "  - inject the SAME values into GitHub: bash scripts/generate-deploy-secrets.sh --from-env $OUT --gh-commands"
