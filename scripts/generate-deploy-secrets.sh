#!/usr/bin/env bash
# ==============================================================================
# 生成 K8s 部署凭据（2026-11-09 第三轮）
#
# 为什么要脚本生成：02-secret.yaml 的注释让运维分别随机生成 database-url 里的
# 口令与 postgres-password，但 17-postgresql.yaml 用 postgres-password 作为
# POSTGRES_PASSWORD 初始化数据库，后端又用 database-url 里的口令去连 —— 两者
# 不一致时清单全部 apply 成功、后端却在鉴权阶段启动失败，且错误发生在部署之后，
# 很难归因。本脚本强制两者同源。
#
# 用法：
#   bash scripts/generate-deploy-secrets.sh --out .env.deploy.k8s
#   bash scripts/generate-deploy-secrets.sh --from-env .env.deploy.k8s --gh-commands
#   bash scripts/generate-deploy-secrets.sh --pg-host <host> --pg-db <db> --pg-user <user>
#
# 输出文件可被 check-deploy-prereqs.sh --env-file 直接读取；
# 默认不打印任何凭据明文，文件权限 600，.env.* 已被 .gitignore 忽略。
# ==============================================================================
set -euo pipefail

OUT=""
FROM_ENV=""
PRINT_GH=0
PG_HOST="postgresql.metaclouds.svc.cluster.local"
PG_PORT="5432"
PG_DB="metaclouds"
PG_USER="metaclouds_user"
SSLMODE="require"

while [ $# -gt 0 ]; do
  case "$1" in
    --out)           OUT="${2:-}"; shift 2 ;;
    --out=*)         OUT="${1#*=}"; shift ;;
    --from-env)      FROM_ENV="${2:-}"; shift 2 ;;
    --from-env=*)    FROM_ENV="${1#*=}"; shift ;;
    --gh-commands)   PRINT_GH=1; shift ;;
    --pg-host)       PG_HOST="${2:-}"; shift 2 ;;
    --pg-port)       PG_PORT="${2:-}"; shift 2 ;;
    --pg-db)         PG_DB="${2:-}"; shift 2 ;;
    --pg-user)       PG_USER="${2:-}"; shift 2 ;;
    --sslmode)       SSLMODE="${2:-}"; shift 2 ;;
    -h|--help)       echo "Usage: $0 [--out <file>] [--from-env <file> --gh-commands] [--pg-host/--pg-db/--pg-user ...]"; exit 0 ;;
    *) echo "::error::unknown argument: $1" >&2; exit 2 ;;
  esac
done

# 纯字母数字随机串：避免 / + = 等字符在 URL、YAML、shell 中需要转义
gen() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9'; }

PG_PASSWORD="$(gen)"
K8S_JWT_SECRET="$(gen)"
K8S_DATABASE_URL="postgresql://${PG_USER}:${PG_PASSWORD}@${PG_HOST}:${PG_PORT}/${PG_DB}?sslmode=${SSLMODE}"
K8S_REDIS_PASSWORD="$(gen)"
K8S_DEFAULT_ADMIN_PASSWORD="$(gen)"
K8S_POSTGRES_PASSWORD="$PG_PASSWORD"
K8S_PROTECTED_ENDPOINTS_TOKEN="$(gen)"

# --from-env：复用已生成的凭据，保证 --gh-commands 注入 GitHub 的值与本地
# --env-file 自检的值完全一致（否则两次运行会生成两套不同的口令）。
if [ -n "$FROM_ENV" ]; then
  if [ ! -f "$FROM_ENV" ]; then
    echo "::error::--from-env file not found: $FROM_ENV" >&2
    exit 2
  fi
  set -a
  # shellcheck disable=SC1090
  . "$FROM_ENV"
  set +a
  for name in K8S_JWT_SECRET K8S_DATABASE_URL K8S_REDIS_PASSWORD \
              K8S_DEFAULT_ADMIN_PASSWORD K8S_POSTGRES_PASSWORD \
              K8S_PROTECTED_ENDPOINTS_TOKEN; do
    if [ -z "${!name:-}" ]; then
      echo "::error::$FROM_ENV is missing $name" >&2
      exit 2
    fi
  done
  # 一致性自检：database-url 里的口令必须与 postgres-password 相同
  URL_PASS="${K8S_DATABASE_URL#*://}"
  URL_PASS="${URL_PASS#*:}"
  URL_PASS="${URL_PASS%%@*}"
  if [ "$URL_PASS" != "$K8S_POSTGRES_PASSWORD" ]; then
    echo "::error::password inside K8S_DATABASE_URL does not match K8S_POSTGRES_PASSWORD" >&2
    exit 2
  fi
fi

if [ "$PRINT_GH" -eq 1 ]; then
  # 明文只在这里出现，且由调用方自行决定是否执行/转发
  printf "gh secret set K8S_JWT_SECRET --body '%s'\n" "$K8S_JWT_SECRET"
  printf "gh secret set K8S_DATABASE_URL --body '%s'\n" "$K8S_DATABASE_URL"
  printf "gh secret set K8S_REDIS_PASSWORD --body '%s'\n" "$K8S_REDIS_PASSWORD"
  printf "gh secret set K8S_DEFAULT_ADMIN_PASSWORD --body '%s'\n" "$K8S_DEFAULT_ADMIN_PASSWORD"
  printf "gh secret set K8S_POSTGRES_PASSWORD --body '%s'\n" "$K8S_POSTGRES_PASSWORD"
  printf "gh secret set K8S_PROTECTED_ENDPOINTS_TOKEN --body '%s'\n" "$K8S_PROTECTED_ENDPOINTS_TOKEN"
  printf '\n# 注意：K8S_POSTGRES_PASSWORD 与 K8S_DATABASE_URL 中的口令由本脚本保证同源。\n' >&2
  exit 0
fi

if [ -z "$OUT" ]; then
  echo "::error::specify --out <file> (or --gh-commands)" >&2
  exit 2
fi

TMP="$(mktemp "${OUT}.XXXXXX")"
chmod 600 "$TMP"
cat > "$TMP" <<EOF
# generated by scripts/generate-deploy-secrets.sh — DO NOT COMMIT
K8S_JWT_SECRET='${K8S_JWT_SECRET}'
K8S_DATABASE_URL='${K8S_DATABASE_URL}'
K8S_REDIS_PASSWORD='${K8S_REDIS_PASSWORD}'
K8S_DEFAULT_ADMIN_PASSWORD='${K8S_DEFAULT_ADMIN_PASSWORD}'
K8S_POSTGRES_PASSWORD='${K8S_POSTGRES_PASSWORD}'
K8S_PROTECTED_ENDPOINTS_TOKEN='${K8S_PROTECTED_ENDPOINTS_TOKEN}'
EOF
mv "$TMP" "$OUT"
chmod 600 "$OUT" 2>/dev/null || true

REPORTED_MODE="$(stat -c '%a' "$OUT" 2>/dev/null || echo unknown)"
echo "generated 6 K8s credentials into $OUT (values redacted, requested mode 600)"
if [ "$REPORTED_MODE" != "600" ]; then
  echo "  [WARN] filesystem reports mode $REPORTED_MODE — Windows/NTFS does not enforce POSIX chmod;"
  echo "         keep this file in a private directory and never commit it (.env.* is gitignored)"
fi
echo "  - K8S_POSTGRES_PASSWORD and the password inside K8S_DATABASE_URL are identical"
echo "  - verify with: bash scripts/check-deploy-prereqs.sh --env-file $OUT --target k8s --report"
echo "  - inject the SAME values into GitHub: bash scripts/generate-deploy-secrets.sh --from-env $OUT --gh-commands"
